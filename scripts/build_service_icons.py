#!/usr/bin/env python3
"""Build the local AWS SVG sprite from a pinned, reviewed official icon map."""
import argparse
import hashlib
import io
import json
from pathlib import Path
import re
from urllib.request import urlopen
from zipfile import ZipFile
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
SVG = 'http://www.w3.org/2000/svg'
XLINK = 'http://www.w3.org/1999/xlink'
ET.register_namespace('', SVG)
ET.register_namespace('xlink', XLINK)


def build(archive):
    manifest = json.loads((ROOT / 'scripts/aws_icon_map.json').read_text())
    ids = {entry['id'] for entry in json.loads((ROOT / 'study/content/aws-services.json').read_text())['entries']}
    assert set(manifest['entries']) == ids, 'Update the icon map to cover the catalog exactly'
    payload = Path(archive).read_bytes() if archive else urlopen(manifest['package'], timeout=60).read()
    assert hashlib.sha256(payload).hexdigest() == manifest['sha256'], 'Unexpected AWS icon package'
    sprite = ET.Element(f'{{{SVG}}}svg')
    sprite.append(ET.Comment(' AWS architecture icons, July 2026. Source: https://aws.amazon.com/architecture/icons/ '))
    symbols = {}
    output = {}
    with ZipFile(io.BytesIO(payload)) as package:
        for entry_id, entry in manifest['entries'].items():
            path = entry['path']
            if path not in symbols:
                symbol_id = 'aws-' + re.sub(r'[^a-z0-9]+', '-', Path(path).stem.lower()).strip('-')
                assert symbol_id not in symbols.values(), 'Duplicate symbol id'
                source = ET.fromstring(package.read(path))
                assert all(el.tag.rsplit('}', 1)[-1] not in {'script', 'foreignObject', 'image'} for el in source.iter())
                # Namespace all internal IDs/references before combining independent SVGs.
                references = set()
                for el in source.iter():
                    for key, value in el.attrib.items():
                        references.update(re.findall(r'url\(#([^)]*)\)', value))
                        if key.rsplit('}', 1)[-1] == 'href' and value.startswith('#'):
                            references.add(value[1:])
                internal = {el.attrib['id']: f'{symbol_id}-{i}' for i, el in enumerate(source.iter()) if el.get('id') in references}
                assert references <= internal.keys(), 'Missing internal SVG reference'
                for el in source.iter():
                    for key, value in list(el.attrib.items()):
                        assert not key.lower().startswith('on'), 'Unexpected event handler'
                        if key == 'id':
                            if value in internal:
                                el.set(key, internal[value])
                            else:
                                del el.attrib[key]
                        elif value.startswith('#') and value[1:] in internal:
                            el.set(key, '#' + internal[value[1:]])
                        else:
                            el.set(key, re.sub(r'url\(#([^)]*)\)', lambda m: f'url(#{internal[m[1]]})', value))
                    el.text = el.text.strip() if el.text and el.text.strip() else None
                    el.tail = None
                symbol = ET.SubElement(sprite, f'{{{SVG}}}symbol', {'id': symbol_id, 'viewBox': source.attrib['viewBox']})
                for child in source:
                    if child.tag != f'{{{SVG}}}title':
                        symbol.append(child)
                symbols[path] = symbol_id
            output[entry_id] = {'symbol': symbols[path], 'scope': entry['scope'], 'label': entry['label']}
    svg_ids = [el.attrib['id'] for el in sprite.iter() if 'id' in el.attrib]
    assert len(svg_ids) == len(set(svg_ids)), 'Duplicate SVG IDs'
    (ROOT / 'study/service-icons.svg').write_text(ET.tostring(sprite, encoding='unicode') + '\n')
    (ROOT / 'study/service-icons.mjs').write_text('// Generated by scripts/build_service_icons.py. AWS artwork: https://aws.amazon.com/architecture/icons/\nexport const serviceIcons = ' + json.dumps(output, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print(f'{len(output)} cards covered by {len(symbols)} official SVG assets')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', help='Use an already downloaded official ZIP')
    build(parser.parse_args().archive)
